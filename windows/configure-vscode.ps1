[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$Vps,
    [int]$VpsSshPort = 22,
    [string]$RemoteClaude = "claude",
    [string]$RemoteWorkdir = "~",
    [string]$RemoteSettings = "",
    [ValidatePattern('^[A-Za-z0-9_-]+$')]
    [string]$WrapperName = "claude-vps-wrapper-history",
    [int]$LocalMcpPort = 8765,
    [int]$RemoteMcpPort = 18765
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path -Parent $PSScriptRoot
$Wrapper = Join-Path $ProjectRoot "bin\$WrapperName.exe"
$Config = Join-Path $ProjectRoot "bin\bridge.conf"

if (-not (Test-Path $Wrapper)) {
    & (Join-Path $PSScriptRoot "build-wrapper.ps1") -OutputName $WrapperName
}

@"
# Generated by windows/configure-vscode.ps1
CLAUDE_VPS_HOST=$Vps
CLAUDE_VPS_SSH_PORT=$VpsSshPort
CLAUDE_VPS_REMOTE_CLAUDE=$RemoteClaude
CLAUDE_VPS_REMOTE_WORKDIR=$RemoteWorkdir
CLAUDE_VPS_SETTINGS=$RemoteSettings
CLAUDE_LOCAL_MCP_PORT=$LocalMcpPort
CLAUDE_VPS_MCP_PORT=$RemoteMcpPort
CLAUDE_VPS_SSH_PATH=C:\Windows\System32\OpenSSH\ssh.exe
"@ | Set-Content -Encoding UTF8 $Config

$SettingsPath = Join-Path $env:APPDATA "Code\User\settings.json"
$SettingsDir = Split-Path -Parent $SettingsPath
New-Item -ItemType Directory -Force -Path $SettingsDir | Out-Null
if (-not (Test-Path $SettingsPath)) {
    "{}" | Set-Content -Encoding UTF8 $SettingsPath
}

function Set-JsoncStringSetting([string]$Text, [string]$Key, [string]$Value) {
    $escapedKey = [regex]::Escape($Key)
    $encodedValue = ConvertTo-Json $Value -Compress
    $pattern = '("' + $escapedKey + '"\s*:\s*)"(?:\\.|[^"\\])*"'
    if ([regex]::IsMatch($Text, $pattern)) {
        return [regex]::Replace($Text, $pattern, ('$1' + $encodedValue), 1)
    }
    $close = $Text.LastIndexOf("}")
    if ($close -lt 0) { throw "VS Code settings.json is not a JSON object" }
    $before = $Text.Substring(0, $close).TrimEnd()
    $after = $Text.Substring($close)
    $separator = if ($before.EndsWith("{") -or $before.EndsWith(",")) { "" } else { "," }
    $nl = [Environment]::NewLine
    return $before + $separator + $nl + "  " + (ConvertTo-Json $Key -Compress) + ": " + $encodedValue + $nl + $after
}

function Set-JsoncBooleanSetting([string]$Text, [string]$Key, [bool]$Value) {
    $escapedKey = [regex]::Escape($Key)
    $literal = if ($Value) { "true" } else { "false" }
    $pattern = '("' + $escapedKey + '"\s*:\s*)(?:true|false)'
    if ([regex]::IsMatch($Text, $pattern)) {
        return [regex]::Replace($Text, $pattern, ('$1' + $literal), 1)
    }
    $close = $Text.LastIndexOf("}")
    if ($close -lt 0) { throw "VS Code settings.json is not a JSON object" }
    $before = $Text.Substring(0, $close).TrimEnd()
    $after = $Text.Substring($close)
    $separator = if ($before.EndsWith("{") -or $before.EndsWith(",")) { "" } else { "," }
    $nl = [Environment]::NewLine
    return $before + $separator + $nl + "  " + (ConvertTo-Json $Key -Compress) + ": " + $literal + $nl + $after
}

$settings = Get-Content -Raw $SettingsPath
$settings = Set-JsoncStringSetting $settings "claudeCode.claudeProcessWrapper" $Wrapper
$settings = Set-JsoncBooleanSetting $settings "claudeCode.disableLoginPrompt" $true
Set-Content -Encoding UTF8 $SettingsPath $settings

Write-Host "Configured Claude Code VS Code process wrapper:"
Write-Host "  $Wrapper"
Write-Host "VPS:"
Write-Host "  $Vps"
Write-Host ""
Write-Host "Reload the VS Code window, then open Claude Code normally."
